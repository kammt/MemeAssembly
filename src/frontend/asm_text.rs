//! The `-S` output: an [`Asm`] that prints GNU as text (Intel syntax) instead of encoding
//! machine code like [`encoder`](super::encoder).

use super::state::CompileState;
use super::log::VERSION_STRING;
use super::translator::{translate, Asm, AsmResult, Imm, Opnd};
use crate::backend::emitter::{Base, Cond, Mem, Op, Reg, SectionKind, Size};
use crate::target::Target;

/// Generates the complete assembly text.
pub fn write_to_string(state: &CompileState) -> Result<Vec<u8>, String> {
    let mut p = Printer {
        out: format!("#\n# Generated by the MemeAssembly compiler {VERSION_STRING}\n#\n.intel_syntax noprefix\n")
            .into_bytes(),
        target: state.target,
        data: false,
        indent: "",
        pending: None,
        files: 0,
    };
    translate(state, &mut p)?;
    p.flush();
    Ok(p.out)
}

/// Collects the assembly text. Labels are kept pending so that they can share a line with the
/// following instruction or directive.
struct Printer {
    out: Vec<u8>,
    target: Target,
    /// In `.data`, labels share the line with the following directive.
    data: bool,
    indent: &'static str,
    /// A label (with its indentation) that shares the line with the next instruction or
    /// directive, if there is one.
    pending: Option<Vec<u8>>,
    /// Number of `.file` entries
    files: usize,
}

impl Printer {
    /// Writes a pending label on a line of its own.
    fn flush(&mut self) {
        if let Some(label) = self.pending.take() {
            self.out.extend_from_slice(&label);
            self.out.push(b'\n');
        }
    }

    /// An instruction or data directive, after the pending label or the indentation.
    fn line(&mut self, text: &[u8]) {
        match self.pending.take() {
            Some(label) => {
                self.out.extend_from_slice(&label);
                self.out.push(b' ');
            }
            None => self.out.extend_from_slice(self.indent.as_bytes()),
        }
        self.out.extend_from_slice(text);
        self.out.push(b'\n');
    }

    /// A directive in the first column.
    fn directive(&mut self, text: &[u8]) {
        self.flush();
        self.out.extend_from_slice(text);
        self.out.push(b'\n');
    }

    fn branch(&mut self, mnemonic: &str, target: &[u8]) {
        let mut text = format!("{mnemonic} ").into_bytes();
        // gas would read `rax`, `byte`, `$`, ... as something other than a symbol
        let quote = !gas_reads_as_symbol(target);
        if quote {
            text.push(b'"');
        }
        text.extend_from_slice(target);
        if quote {
            text.push(b'"');
        }
        self.line(&text);
    }
}

/// `jmp`, or the conditional jump for `cond` (`jge`, ...).
fn jump_mnemonic(cond: Option<Cond>) -> String {
    match cond {
        None => "jmp".to_string(),
        Some(c) => format!("j{c:?}").to_ascii_lowercase(),
    }
}

/// An immediate operand: decimal, `0x` and upper-case hex, or its source text (e.g. a character
/// constant).
fn imm_text(imm: Imm) -> Vec<u8> {
    match imm {
        Imm::Dec(v) => v.to_string().into_bytes(),
        Imm::Hex(v) => format!("0x{:X}", v as u64).into_bytes(),
        Imm::Text(_, text) => text.to_vec(),
    }
}

/// A memory operand in Intel syntax, e.g. `BYTE PTR [rip + sym + 8]`.
fn mem_text(m: &Mem) -> String {
    let size = match m.size {
        None => "",
        Some(Size::Byte) => "BYTE PTR ",
        Some(Size::Word) => "WORD PTR ",
        Some(Size::Dword) => "DWORD PTR ",
        Some(Size::Qword) => "QWORD PTR ",
    };
    let disp = if m.disp == 0 { String::new() } else { format!(" + {}", m.disp) };
    match &m.base {
        Base::Reg(r) => format!("{size}[{}{disp}]", r.name()),
        Base::Rip(symbol) => format!("{size}[rip + {symbol}{disp}]"),
        Base::Abs => format!("{size}[{}]", m.disp),
    }
}

/// Whether gas reads the bare identifier `name` as a symbol when it is a branch target (and not
/// as the current address `$`/`.`, a register, the `flat` pseudo register, an operator like
/// `and`/`not` or a constant like `byte`/`near`).
fn gas_reads_as_symbol(name: &[u8]) -> bool {
    let l = String::from_utf8_lossy(name).to_ascii_lowercase();
    // `<prefix>N` with min <= N <= max, without leading zeros
    let numbered = |s: &str, prefix: &str, min: u32, max: u32| {
        s.strip_prefix(prefix).is_some_and(|n| {
            !n.is_empty()
                && (n.len() == 1 || !n.starts_with('0'))
                && n.chars().all(|c| c.is_ascii_digit())
                && n.parse::<u32>().is_ok_and(|v| (min..=max).contains(&v))
        })
    };
    // APX registers r16..r31 (+ w/d/b forms)
    let apx = ["", "w", "d", "b"]
        .iter()
        .any(|suffix| l.strip_suffix(suffix).is_some_and(|base| numbered(base, "r", 16, 31)));
    !(Reg::parse(&l).is_some()
        || apx
        || numbered(&l, "xmm", 0, 31)
        || numbered(&l, "ymm", 0, 31)
        || numbered(&l, "zmm", 0, 31)
        || numbered(&l, "tmm", 0, 7)
        || numbered(&l, "mm", 0, 7)
        || numbered(&l, "k", 0, 7)
        || numbered(&l, "cr", 0, 15)
        || numbered(&l, "dr", 0, 15)
        || matches!(
            l.as_str(),
            "$" | "." | "st" | "es" | "cs" | "ss" | "ds" | "fs" | "gs" | "rip" | "eip" | "flat"
                | "and" | "or" | "xor" | "mod" | "shl" | "shr" | "eq" | "ne" | "lt" | "le" | "gt"
                | "ge" | "not" | "byte" | "word" | "dword" | "fword" | "qword" | "mmword" | "tbyte"
                | "oword" | "xmmword" | "ymmword" | "zmmword" | "offset" | "short" | "near" | "far"
        ))
}

impl Asm for Printer {
    fn insn(&mut self, op: Op, ops: &[Opnd]) -> AsmResult {
        let mut text = format!("{op:?}").to_ascii_lowercase().into_bytes();
        for (i, operand) in ops.iter().enumerate() {
            text.extend_from_slice(if i == 0 { b" " } else { b", " });
            match operand {
                Opnd::Reg(r) => text.extend_from_slice(r.name().as_bytes()),
                Opnd::Imm(imm) => text.extend_from_slice(&imm_text(*imm)),
                Opnd::Mem(m) => text.extend_from_slice(mem_text(m).as_bytes()),
            }
        }
        self.line(&text);
        Ok(())
    }
    fn jump(&mut self, cond: Option<Cond>, target: &[u8]) -> AsmResult {
        self.branch(&jump_mnemonic(cond), target);
        Ok(())
    }
    fn jump_local(&mut self, cond: Option<Cond>, n: u32, forward: bool) -> AsmResult {
        let text = format!("{} {n}{}", jump_mnemonic(cond), if forward { 'f' } else { 'b' });
        self.line(text.as_bytes());
        Ok(())
    }
    fn call(&mut self, target: &[u8]) -> AsmResult {
        self.branch("call", target);
        Ok(())
    }
    fn label(&mut self, name: &[u8]) -> AsmResult {
        self.flush();
        let label = [self.indent.as_bytes(), name, b":"].concat();
        if self.data {
            self.pending = Some(label);
        } else {
            self.directive(&label);
        }
        Ok(())
    }
    fn local_label(&mut self, n: u32) {
        self.flush();
        self.pending = Some(format!("{}{n}:", self.indent).into_bytes());
    }
    fn global(&mut self, name: &[u8]) {
        self.directive(&[b".global ", name].concat());
    }
    fn extern_symbol(&mut self, name: &str) {
        self.directive(format!(".extern {name}").as_bytes());
    }
    fn section(&mut self, kind: SectionKind) {
        self.data = kind == SectionKind::Data;
        self.directive(if self.data { b".data" } else { b".text" });
    }
    fn ascii(&mut self, data: &[u8]) {
        let mut text = b".ascii \"".to_vec();
        for &c in data {
            if c == b'"' || c == b'\\' {
                text.push(b'\\');
            }
            text.push(c);
        }
        text.push(b'"');
        self.line(&text);
    }
    fn zeros(&mut self, n: usize) {
        self.line(format!(".byte {}", vec!["0"; n].join(", ")).as_bytes());
    }
    fn quad(&mut self, values: &[Imm]) {
        let values: Vec<Vec<u8>> = values.iter().map(|v| imm_text(*v)).collect();
        self.line(&[&b".quad "[..], &values.join(&b", "[..])].concat());
    }
    fn align(&mut self, bytes: u64) -> AsmResult {
        // On Mach-O, `.align n` means 2**n (and n >= 32 is rejected)
        let directive = if self.target == Target::MacOS {
            format!(".p2align {}", bytes.trailing_zeros())
        } else {
            format!(".align {bytes}")
        };
        self.directive(directive.as_bytes());
        Ok(())
    }
    /// `.file N "path"` for gas' DWARF line tables; `N` is the number later `.loc`s refer to.
    fn debug_file(&mut self, path: &[u8]) -> usize {
        self.files += 1;
        let mut text = format!(".file {} \"", self.files).into_bytes();
        for &c in path {
            if c == b'"' || c == b'\\' {
                text.push(b'\\');
            }
            text.push(c);
        }
        text.push(b'"');
        self.directive(&text);
        self.files
    }
    fn debug_line(&mut self, file: usize, line: u32) {
        self.directive(format!("\t.loc {file} {line}").as_bytes());
    }
    fn char_in_symbol(&self, value: u8, text: &[u8], verbatim: bool) -> Vec<u8> {
        if verbatim {
            text.to_vec()
        } else {
            value.to_string().into_bytes()
        }
    }
    fn indent(&mut self, indent: &'static str) {
        self.indent = indent;
    }
    fn blank(&mut self) {
        self.directive(b"");
    }
    fn gap(&mut self) {
        self.directive(self.indent.as_bytes());
    }
    fn end_line(&mut self) {
        self.flush();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn symbols_gas_would_misread() {
        for name in ["$", ".", "rax", "RAX", "r8", "r15d", "r31b", "xmm0", "ah", "and", "byte", "QWORD", "st", "fs", "rip", "flat", "near"] {
            assert!(!gas_reads_as_symbol(name.as_bytes()), "{name}");
        }
        for name in ["main", "foo", "r32", "r08", "r", "xmm32", "rax1", "st0", "_and", "bytes", "foo$bar", ".L'a'Wins_0"] {
            assert!(gas_reads_as_symbol(name.as_bytes()), "{name}");
        }
    }

    #[test]
    fn layout() {
        let mut p = Printer { out: Vec::new(), target: Target::MacOS, data: false, indent: "\t", pending: None, files: 0 };
        p.local_label(1);
        p.call(b"$").unwrap();
        p.local_label(2);
        p.gap();
        p.insn(Op::Mov, &[Opnd::Mem(Mem { size: Some(Size::Byte), base: Base::Rip(".Lc".into()), disp: 0 }), Opnd::Imm(Imm::Text(97, b"'a'"))]).unwrap();
        p.insn(Op::Movups, &[Opnd::Mem(Mem { size: None, base: Base::Reg(Reg::R64(4)), disp: 8 }), Opnd::Reg(Reg::Xmm(0))]).unwrap();
        p.jump(Some(Cond::Ge), b".L0x45Wins_0").unwrap();
        p.section(SectionKind::Data);
        p.label(b".La").unwrap();
        p.label(b".Lb").unwrap();
        p.quad(&[Imm::Hex(-1), Imm::Dec(0)]);
        p.align(1 << 29).unwrap();
        assert_eq!(
            String::from_utf8(p.out).unwrap(),
            "\t1: call \"$\"\n\t2:\n\t\n\tmov BYTE PTR [rip + .Lc], 'a'\n\tmovups [rsp + 8], xmm0\n\tjge .L0x45Wins_0\n\
             .data\n\t.La:\n\t.Lb: .quad 0xFFFFFFFFFFFFFFFF, 0\n.p2align 29\n"
        );
    }
}
